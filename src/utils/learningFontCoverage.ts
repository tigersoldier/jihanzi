const coverage = Uint8Array.from(atob(COVERAGE_BASE64), character => character.charCodeAt(0))

export function isLearningKaiGlyphSupported(character: string): boolean {
  const codePoints = Array.from(character)
  if (codePoints.length !== 1) return false

  const codePoint = codePoints[0]?.codePointAt(0)
  if (codePoint === undefined || codePoint < HAN_START || codePoint > HAN_END) return false

  const offset = codePoint - HAN_START
  return (coverage[offset >> 3] & (1 << (offset & 7))) !== 0
}
